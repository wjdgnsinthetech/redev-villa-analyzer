/**
 * zone의 city + district에서 LAWD_CD와 동 이름 추출
 * district 형식: "동작구 흑석동"
 */
export function parseLawdInfo(city: string, district: string): { lawdCd: string; dong: string } | null {
  const parts = district.split(" ");
  if (parts.length < 2) return null;

  const gu = parts[0]; // e.g., "동작구"
  const dong = parts.slice(1).join(" "); // e.g., "흑석동"

  const key = `${city} ${gu}`;
  const lawdCd = LAWD_CODES[key];

  if (!lawdCd) return null;

  return { lawdCd, dong };
}
